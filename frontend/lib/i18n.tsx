const dicts = { fa, en };

type Ctx = {
  locale: Locale; t: Dict; setLocale: (l: Locale) => void;
  n: (v: number) => string; money: (v: number) => string;
  date: (iso: string, o?: Intl.DateTimeFormatOptions) => string;
  pick: (o: object, key: string) => string;
  /** localize a digit string (for input display): Persian digits in fa */
  d: (s: string) => string;
};
const LocaleCtx = createContext<Ctx | null>(null);

export function LocaleProvider({ initial, children }: { initial: Locale; children: React.ReactNode }) {
  const [locale, setState] = useState<Locale>(initial);
  const setLocale = useCallback((l: Locale) => {
    document.cookie = `cb_locale=${l}; path=/; max-age=31536000; samesite=lax`;
    document.documentElement.lang = l;
    document.documentElement.dir = l === "fa" ? "rtl" : "ltr";
    setState(l);
  }, []);
  const value = useMemo<Ctx>(() => {
    const nf = new Intl.NumberFormat(locale === "fa" ? "fa-IR" : "en-US");
    const tag = locale === "fa" ? "fa-IR-u-ca-persian" : "en-US";
    return {
      locale, t: dicts[locale], setLocale,
      n: (v) => nf.format(v),
      money: (v) => `${nf.format(v)} ${dicts[locale].common.toman}`,
      date: (iso, o = { day: "numeric", month: "long" }) => new Intl.DateTimeFormat(tag, o).format(new Date(iso)),
      // pick(obj, "name") -> obj.name_fa / obj.name_en
      d: (s) => (locale === "fa" ? s.replace(/\d/g, (x) => "۰۱۲۳۴۵۶۷۸۹"[+x]) : s),
      pick: (o, key) => { const r = o as Record<string, unknown>; return String(r[`${key}_${locale}`] ?? r[`${key}_fa`] ?? ""); },
    };
  }, [locale, setLocale]);
  return <LocaleCtx.Provider value={value}>{children}</LocaleCtx.Provider>;
}

export function useT() {
  const c = useContext(LocaleCtx);
  if (!c) throw new Error("useT outside LocaleProvider");
  return c;
}

